# src/build/gen-abi-bindings.ps1, render the embed ABI's bindings from the ONE description of it.
#
# WHY THIS EXISTS: every host of ScriptLangCore.dll used to re-declare the exports by hand, so the same signature
# lived in src/embed/Program.cs for the harness, in the Python and PowerShell samples on the embedding page, and in
# the C launcher's GetProcAddress table, and nothing compared them. docs/embed/abi.json is now the single statement of
# what the library answers (names, signatures, directions, since-revisions, capability bits), and this script renders
# it into the files under bindings/. Edit the manifest and regenerate; never edit a generated file.
#
# USAGE
#   powershell -NoProfile -File src/build/gen-abi-bindings.ps1           # write the bindings
#   powershell -NoProfile -File src/build/gen-abi-bindings.ps1 -Check    # compare, write nothing
#
# EXIT CODES: 0 written, or everything already current; 1 -Check found a stale or missing binding; 2 the manifest
# itself is missing or unusable.
#
# The comparison normalises line endings, because git checks these files out with the platform's convention
# (core.autocrlf) while this script always writes LF: a difference in newline style is not a stale binding.

param([switch]$Check)

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$manifestPath = Join-Path $root "docs/embed/abi.json"

if (-not (Test-Path -LiteralPath $manifestPath)) {
    Write-Host "no manifest at '$manifestPath'" -ForegroundColor Red
    exit 2
}

try {
    $manifest = Get-Content -LiteralPath $manifestPath -Raw -Encoding UTF8 | ConvertFrom-Json
} catch {
    Write-Host "the manifest is not usable JSON: $($_.Exception.Message)" -ForegroundColor Red
    exit 2
}

$abi = [int]$manifest.abi
$exports = @($manifest.exports)
$capabilities = @($manifest.capabilities)
$generated = @($manifest.generated)

# ONE line of provenance, in each language's own comment style. The file's first line says where it came from, so a
# host that finds a bug in a binding knows what to change.
$provenance = "ScriptLangCore embed ABI $abi, GENERATED by src/build/gen-abi-bindings.ps1 from docs/embed/abi.json: do not edit"

function Get-CSharpType([string]$c) {
    switch ($c) {
        "int" { return "int" }
        "int64_t" { return "long" }
        "char*" { return "nint" }
        "const char*" { return "nint" }
        "void*" { return "nint" }
        "const void*" { return "nint" }
        default { throw "the manifest uses a C type this generator does not know: '$c'" }
    }
}

function Get-PythonType([string]$c) {
    switch ($c) {
        "int" { return "ctypes.c_int" }
        "int64_t" { return "ctypes.c_int64" }
        "char*" { return "ctypes.c_char_p" }
        "const char*" { return "ctypes.c_char_p" }
        "void*" { return "ctypes.c_void_p" }
        "const void*" { return "ctypes.c_void_p" }
        default { throw "the manifest uses a C type this generator does not know: '$c'" }
    }
}

# slc_run_text_async -> RunTextAsync, the name a .NET host reads.
function Get-DotNetName([string]$export) {
    $parts = $export -split "_"
    $name = ""
    for ($i = 1; $i -lt $parts.Count; $i++) {
        $part = $parts[$i]
        $name += $part.Substring(0, 1).ToUpperInvariant() + $part.Substring(1)
    }
    return $name
}

function Get-CapabilityMacro([string]$capability) {
    return "SLC_CAP_" + $capability.ToUpperInvariant()
}

# The parameters of one export, in the manifest's order, skipping the JSON parser's empty array (PowerShell answers
# $null for a property that held []).
function Get-Params($export) {
    $list = @()
    foreach ($p in @($export.params)) {
        if ($null -ne $p) { $list += $p }
    }
    return $list
}

function Test-WritesIntoCallerBuffer($export) {
    foreach ($p in (Get-Params $export)) {
        if ("$($p.dir)" -eq "out") { return $true }
    }
    return $false
}

function Get-OneLine([string]$text) {
    return ($text -replace "\s+", " ").Trim()
}

# ── the C header ─────────────────────────────────────────────────────────────────────────────────────────────────────
function New-CHeader {
    $out = New-Object System.Collections.Generic.List[string]
    $out.Add("/* $provenance")
    $out.Add(" *")
    $out.Add(" * WHAT THIS IS: the declarations a native host compiles against, plus the capability bits it may test.")
    $out.Add(" * Load ScriptLangCore.dll, resolve each name with GetProcAddress, and follow the order on")
    $out.Add(" * docs/embed/howto.html: slc_create, slc_set_output, a run verb, slc_call, slc_last_result, slc_free.")
    $out.Add(" *")
    $out.Add(" * THE CONVENTIONS, which every call below obeys:")
    $out.Add(" *   strings    UTF-8, NUL-terminated. An input is the caller's and is read only for the call. An output")
    $out.Add(" *              goes into a CALLER-OWNED buffer with the snprintf convention: the call answers the length")
    $out.Add(" *              it NEEDS (excluding the terminator), writes at most capacity - 1 bytes plus the terminator,")
    $out.Add(" *              and answers the same length for capacity 0, so one probe sizes the buffer.")
    $out.Add(" *   statuses   the engine's exit codes: 0 ok, 1 failed, 2 usage, 3 refused. A script's own exit(n) is n.")
    $out.Add(" *   handles    opaque int64_t, never reused. 0 is not a session: it is the calling thread's last")
    $out.Add(" *              slc_create failure. slc_free answering 3 means a run is in flight, so retry later.")
    $out.Add(" *   threads    one call at a time per handle; slc_cancel is the one exception by design.")
    $out.Add(" */")
    $out.Add("#ifndef SCRIPTLANGCORE_H")
    $out.Add("#define SCRIPTLANGCORE_H")
    $out.Add("")
    $out.Add("#include <stdint.h>")
    $out.Add("")
    $out.Add("#ifdef __cplusplus")
    $out.Add("extern ""C"" {")
    $out.Add("#endif")
    $out.Add("")
    $out.Add("/* The ABI revision this header describes. A host that sees a different number through slc_abi_revision")
    $out.Add(" * should check the call it needs before making it rather than hope. */")
    $out.Add("#define SLC_ABI_REVISION $abi")
    $out.Add("")
    $out.Add("/* The capability bits slc_capabilities() answers, one per group of calls. Test a bit instead of probing an")
    $out.Add(" * export and treating a null as a crash; a bit says what THIS build answers, which is why the COM server's")
    $out.Add(" * is absent from an image that does not compile it. */")
    foreach ($cap in $capabilities) {
        $bit = [int]$cap.bit
        $value = [int]([math]::Pow(2, $bit))
        $out.Add("#define $(Get-CapabilityMacro $cap.name) (1 << $bit) /* since ABI $($cap.since): $(Get-OneLine $cap.summary) */")
    }
    $out.Add("")
    $out.Add("/* The line callback slc_set_output installs: channel 0 is the script's print, 1 is the engine's own log")
    $out.Add(" * lines. The string is valid only for the duration of the call, and it runs on the thread that runs the")
    $out.Add(" * script. */")
    $out.Add("typedef void (*slc_line_cb)(int64_t handle, int32_t channel, const char* utf8, void* user);")
    foreach ($export in $exports) {
        $params = @()
        foreach ($p in (Get-Params $export)) {
            $params += "$($p.type) $($p.name)"
        }
        $note = ""
        if (Test-WritesIntoCallerBuffer $export) {
            $note = " Writes into the caller's buffer and answers the length it needs."
        }
        # A C declaration with no parameters says `(void)`: `()` means "unspecified arguments" in C, which is the one
        # place the header must not be casual.
        $declared = if ($params.Count -eq 0) { "(void)" } else { "($($params -join ', '))" }
        $out.Add("")
        $out.Add("/* $(Get-OneLine $export.summary)")
        $out.Add(" * Since ABI $($export.since).$note */")
        $out.Add("$($export.returns) $($export.name)$declared;")
    }
    $out.Add("")
    $out.Add("#ifdef __cplusplus")
    $out.Add("}")
    $out.Add("#endif")
    $out.Add("")
    $out.Add("#endif /* SCRIPTLANGCORE_H */")
    return ($out -join "`n") + "`n"
}

# ── the C# bindings ──────────────────────────────────────────────────────────────────────────────────────────────────
function New-CSharpBindings {
    $out = New-Object System.Collections.Generic.List[string]
    $out.Add("// $provenance")
    $out.Add("//")
    $out.Add("// WHAT THIS IS: one delegate per export, so a managed host binds the published library with NativeLibrary")
    $out.Add("// and needs no generated interop of its own, and one constant per export name, so a GetProcAddress site")
    $out.Add("// cannot misspell a name into a runtime null. The embed harness (src/embed) compiles this file, which is")
    $out.Add("// what keeps the harness's own declarations from drifting away from the manifest.")
    $out.Add("namespace ScriptLangCore.Abi;")
    $out.Add("")
    $out.Add("/// <summary>The ABI revision and the export names, as constants.</summary>")
    $out.Add("internal static class AbiExports")
    $out.Add("{")
    $out.Add("    /// <summary>The revision this file describes, i.e. what slc_abi_revision answers for this contract.</summary>")
    $out.Add("    internal const int Revision = $abi;")
    foreach ($export in $exports) {
        $constant = Get-DotNetName $export.name
        $out.Add("")
        $out.Add("    /// <summary>``$($export.name)``: $(Get-OneLine $export.summary)</summary>")
        $out.Add("    internal const string $constant = ""$($export.name)"";")
    }
    $out.Add("}")
    $out.Add("")
    $out.Add("/// <summary>The capability bits, so a host tests `AbiCapabilities.Async` rather than a magic number. They")
    $out.Add("/// describe what a BUILD answers, not what the engine can do: `Com` is set only by the Embed configuration,")
    $out.Add("/// which is the one that compiles the in-proc COM server.</summary>")
    $out.Add("internal static class AbiCapabilities")
    $out.Add("{")
    $bitExpressions = @()
    foreach ($cap in $capabilities) {
        $constant = Get-DotNetName ("slc_" + $cap.name)
        $bit = [int]$cap.bit
        $bitExpressions += $constant
        $out.Add("    /// <summary>Since ABI $($cap.since): $(Get-OneLine $cap.summary)</summary>")
        $out.Add("    internal const int $constant = 1 << $bit;")
    }
    $out.Add("")
    $out.Add("    /// <summary>Every bit this contract knows, which is what a full build answers.</summary>")
    $out.Add("    internal const int All = $($bitExpressions -join ' | ');")
    $out.Add("}")
    foreach ($export in $exports) {
        $delegate = (Get-DotNetName $export.name) + "Fn"
        $signature = @()
        foreach ($p in (Get-Params $export)) {
            $signature += "$(Get-CSharpType $p.type) $($p.name)"
        }
        $out.Add("")
        $out.Add("/// <summary>``$($export.name)``: $(Get-OneLine $export.summary)")
        $out.Add("/// Since ABI $($export.since).</summary>")
        $out.Add("internal delegate $(Get-CSharpType $export.returns) $delegate($($signature -join ', '));")
    }
    return ($out -join "`n") + "`n"
}

# ── the Python bindings ──────────────────────────────────────────────────────────────────────────────────────────────
function New-PythonBindings {
    $out = New-Object System.Collections.Generic.List[string]
    # The triple quote as a variable, because a run of quotes inside a PowerShell string is unreadable and this file
    # emits quite a few of them.
    $tq = '"""'
    $out.Add($tq + $provenance + ".")
    $out.Add("")
    $out.Add("HOW A HOST USES IT")
    $out.Add("    import scriptlangcore")
    $out.Add("    lib = scriptlangcore.load(r""ScriptLangCore.dll"")")
    $out.Add("    print(scriptlangcore.ABI_REVISION, lib.slc_abi_revision())")
    $out.Add("    print(scriptlangcore.text(lib.slc_version))")
    $out.Add("    session = lib.slc_create(b'{""thread"":""own""}')")
    $out.Add("    lib.slc_run_text(session, b'print(1 + 1)', None)")
    $out.Add("    print(scriptlangcore.text(lib.slc_last_result, session))")
    $out.Add("    lib.slc_free(session)")
    $out.Add("")
    $out.Add("EVERY CALL OBEYS THE MANIFEST'S CONVENTIONS: strings are UTF-8 and NUL-terminated, an output goes into a")
    $out.Add("caller-owned buffer following the snprintf convention (which is what text() does for you), and a status is")
    $out.Add("the engine's exit code: 0 ok, 1 failed, 2 usage, 3 refused.")
    $out.Add($tq)
    $out.Add("from __future__ import annotations")
    $out.Add("")
    $out.Add("import ctypes")
    $out.Add("import os")
    $out.Add("")
    $out.Add("ABI_REVISION = $abi")
    $out.Add("")
    foreach ($cap in $capabilities) {
        $constant = "CAP_" + $cap.name.ToUpperInvariant()
        $bit = [int]$cap.bit
        $out.Add("# Since ABI $($cap.since): $(Get-OneLine $cap.summary)")
        $out.Add("$constant = 1 << $bit")
    }
    $out.Add("")
    $out.Add("CAPABILITIES = {")
    foreach ($cap in $capabilities) {
        $constant = "CAP_" + $cap.name.ToUpperInvariant()
        $out.Add("    ${constant}: ""$($cap.name)"",")
    }
    $out.Add("}")
    $out.Add("")
    $out.Add("# name -> (return type, [parameter types]), which is what ctypes needs and all it needs.")
    $out.Add("_SIGNATURES = {")
    foreach ($export in $exports) {
        $types = @()
        foreach ($p in (Get-Params $export)) { $types += (Get-PythonType $p.type) }
        $out.Add("    ""$($export.name)"": ($(Get-PythonType $export.returns), [$($types -join ', ')]),")
    }
    $out.Add("}")
    $out.Add("")
    $out.Add("")
    $out.Add("def load(path: str) -> ctypes.CDLL:")
    $out.Add("    " + $tq + "Loads the engine and binds every export's types, so a call can be made with plain Python values.")
    $out.Add("")
    $out.Add("    A wrong argument count then raises TypeError at the call site instead of corrupting the stack, which is")
    $out.Add("    the whole reason the manifest carries the signatures.")
    $out.Add("    " + $tq)
    $out.Add("    library = ctypes.WinDLL(path) if os.name == ""nt"" else ctypes.CDLL(path)")
    $out.Add("    for name, (restype, argtypes) in _SIGNATURES.items():")
    $out.Add("        export = getattr(library, name)")
    $out.Add("        export.restype = restype")
    $out.Add("        export.argtypes = argtypes")
    $out.Add("    return library")
    $out.Add("")
    $out.Add("")
    $out.Add("def text(export, *arguments) -> str:")
    $out.Add("    " + $tq + "Reads one of the exports that fills a caller-owned buffer: probes for its length, then reads it.")
    $out.Add("")
    $out.Add("    The buffer arguments are the LAST two of every such export, which is the manifest's shape")
    $out.Add("    (slc_last_result(handle, buffer, capacity)), so a caller passes only what comes before them.")
    $out.Add("    " + $tq)
    $out.Add("    needed = export(*arguments, None, 0)")
    $out.Add("    buffer = ctypes.create_string_buffer(needed + 1)")
    $out.Add("    export(*arguments, buffer, needed + 1)")
    $out.Add("    return buffer.value.decode(""utf-8"")")
    $out.Add("")
    $out.Add("")
    $out.Add("def capabilities(mask: int) -> list[str]:")
    $out.Add("    " + $tq + "The names of the capability bits set in the mask slc_capabilities answers." + $tq)
    $out.Add("    return [name for bit, name in CAPABILITIES.items() if mask & bit]")
    return ($out -join "`n") + "`n"
}

# ── the Java carrier ────────────────────────────────────────────────────────────────────────────────────────────────
# slc_run_text_async -> runTextAsync, the name the wrapper carries. The MethodHandle keeps the ABI's own name, so a
# host that needs a shape the wrapper does not offer still has the export by the name the manifest gives it.
function Get-JavaWrapperName([string]$export) {
    $parts = $export -split "_"
    $name = $parts[1]
    for ($i = 2; $i -lt $parts.Count; $i++) {
        $name += $parts[$i].Substring(0, 1).ToUpperInvariant() + $parts[$i].Substring(1)
    }
    return $name
}

function Get-JavaType([string]$c) {
    switch ($c) {
        "int" { return "int" }
        "int64_t" { return "long" }
        # a Java String in, a MemorySegment out: the wrappers marshal the first and hand the second through untouched
        "char*" { return "MemorySegment" }
        "const char*" { return "MemorySegment" }
        "void*" { return "MemorySegment" }
        "const void*" { return "MemorySegment" }
        default { throw "the manifest uses a C type this generator does not know: '$c'" }
    }
}

function Get-JavaLayout([string]$c) {
    switch ($c) {
        "int" { return "ValueLayout.JAVA_INT" }
        "int64_t" { return "ValueLayout.JAVA_LONG" }
        "char*" { return "ValueLayout.ADDRESS" }
        "const char*" { return "ValueLayout.ADDRESS" }
        "void*" { return "ValueLayout.ADDRESS" }
        "const void*" { return "ValueLayout.ADDRESS" }
        default { throw "the manifest uses a C type this generator does not know: '$c'" }
    }
}

function New-JavaBindings {
